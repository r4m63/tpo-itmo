r.h2("Page Object Model")
r.text(
    "Базовый класс BasePage инкапсулирует ожидания и работу с элементами через WebDriverWait. "
    "Поддерживаются как обычный click, так и jsClick через JavascriptExecutor для случаев, "
    "когда элемент перекрыт всплывающим баннером (актуально для Firefox)."
)

r.code(
    "abstract class BasePage {\n"
    "    protected WebElement waitForVisible(By locator) {\n"
    "        return wait.until(ExpectedConditions.visibilityOfElementLocated(locator));\n"
    "    }\n"
    "\n"
    "    protected void click(By locator) {\n"
    "        waitForClickable(locator).click();\n"
    "    }\n"
    "\n"
    "    protected void jsClick(By locator) {\n"
    "        WebElement element = waitForVisible(locator);\n"
    "        ((JavascriptExecutor) driver)\n"
    "            .executeScript(\"arguments[0].scrollIntoView({block:'center'});\", element);\n"
    "        ((JavascriptExecutor) driver)\n"
    "            .executeScript(\"arguments[0].click();\", element);\n"
    "    }\n"
    "}"
)

